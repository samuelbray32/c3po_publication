"""Prepare native LFADS input and export its posterior-averaged factors."""

from pathlib import Path

import h5py
import numpy as np
from numpy.typing import NDArray


def write_lfads_data(
    count_blocks: list[NDArray[np.float32]],
    time_blocks: list[NDArray[np.float64]],
    path: str,
    sequence_bins: int = 120,
    valid_fraction: float = 0.2,
) -> dict[str, int]:
    """Write nonoverlapping sequences in lfads-torch's native HDF5 format.

    Parameters
    ----------
    count_blocks : list of numpy.ndarray
        Raw counts per uninterrupted interval, shaped (n_bins, n_units).
    time_blocks : list of numpy.ndarray
        Corresponding bin-center timestamps in seconds, shaped (n_bins,).
    path : str or pathlib.Path
        New input HDF5 file. Existing files are rejected.
    sequence_bins : int, default=120
        Bins per sequence. Short intervals and incomplete tails are omitted.
    valid_fraction : float, default=0.2
        Last fraction of eligible intervals reserved for validation. All
        sequences from an interval belong to the same split.

    Returns
    -------
    summary : dict of str to int
        Sequence dimensions, split sizes, and included/omitted bin counts.
        HDF5 arrays are shaped (n_sequences_in_split, sequence_bins, n_units).
        Time arrays are shaped (n_sequences_in_split, sequence_bins).
    """
    if len(count_blocks) != len(time_blocks) or not count_blocks:
        raise ValueError("Provide matching nonempty count and time blocks.")
    if not isinstance(sequence_bins, int) or sequence_bins < 1:
        raise ValueError("sequence_bins must be a positive integer.")
    if not 0 < valid_fraction < 1:
        raise ValueError("valid_fraction must be between zero and one.")
    n_units = count_blocks[0].shape[1]
    counts, times, intervals = [], [], []
    for interval_id, (block, time) in enumerate(zip(count_blocks, time_blocks)):
        if block.ndim != 2 or block.shape != (len(time), n_units):
            raise ValueError("Each count block must match its timestamps and units.")
        if not np.isfinite(block).all() or np.any(block < 0) or np.any(block % 1):
            raise ValueError("LFADS Poisson input must contain nonnegative counts.")
        if not np.isfinite(time).all() or np.any(np.diff(time) <= 0):
            raise ValueError("Timestamps must be finite and increasing.")
        n_sequences = len(block) // sequence_bins
        if n_sequences:
            stop = n_sequences * sequence_bins
            counts.append(block[:stop].reshape(n_sequences, sequence_bins, n_units))
            times.append(time[:stop].reshape(n_sequences, sequence_bins))
            intervals.append(np.full(n_sequences, interval_id, dtype=np.int64))
    if len(counts) < 2:
        raise ValueError("At least two intervals must contain a complete sequence.")
    counts = np.concatenate(counts).astype(np.float32)
    times = np.concatenate(times)
    interval_id = np.concatenate(intervals)
    if np.any(np.diff(times.ravel()) <= 0):
        raise ValueError("Intervals must be in chronological order without overlap.")
    eligible = np.unique(interval_id)
    n_valid = min(
        len(eligible) - 1, max(1, int(np.ceil(len(eligible) * valid_fraction)))
    )
    valid = np.isin(interval_id, eligible[-n_valid:])
    path = Path(path).expanduser()
    path.parent.mkdir(parents=True, exist_ok=True)
    with h5py.File(path, "x") as output:
        output.create_dataset("unit_index", data=np.arange(n_units))
        for split, mask in (("train", ~valid), ("valid", valid)):
            key = f"{split}_encod_data"
            output.create_dataset(key, data=counts[mask], compression="gzip")
            output[f"{split}_recon_data"] = output[key]
            output.create_dataset(f"{split}_time", data=times[mask])
            output.create_dataset(f"{split}_segment_id", data=interval_id[mask])
            output.create_dataset(f"{split}_sequence_id", data=np.flatnonzero(mask))
    return {
        "n_units": n_units,
        "sequence_bins": sequence_bins,
        "n_train": int(np.sum(~valid)),
        "n_valid": int(np.sum(valid)),
        "included_bins": int(times.size),
        "omitted_bins": int(sum(len(x) for x in count_blocks) - times.size),
    }


def export_lfads_latent(
    posterior_path: str,
    output_path: str,
    bin_seconds: float = 1 / 120,
) -> dict[str, NDArray]:
    """Export native posterior-averaged factors, preserving time and split labels.

    Parameters
    ----------
    posterior_path : str or pathlib.Path
        File generated by lfads-torch's ``run_posterior_sampling``.
    output_path : str or pathlib.Path
        New compressed NPZ file. Existing files are rejected.
    bin_seconds : float, default=1/120
        Input bin duration in seconds; LFADS outputs at the same resolution.

    Returns
    -------
    results : dict of str to numpy.ndarray
        ``latent`` has shape (n_time, n_factors). ``time``, ``segment_id``,
        ``sequence_id``, and ``split`` have shape (n_time,). Split 0 means
        training, 1 validation. ``unit_index`` has shape (n_units,). Bin
        durations are scalar arrays. All time-indexed arrays are chronological.
    """
    if not np.isfinite(bin_seconds) or bin_seconds <= 0:
        raise ValueError("bin_seconds must be positive and finite.")
    arrays = {
        key: [] for key in ("latent", "time", "segment_id", "sequence_id", "split")
    }
    with h5py.File(posterior_path, "r") as source:
        unit_index = source["unit_index"][()]
        for label, split in enumerate(("train", "valid")):
            factors = source[f"{split}_factors"][()]
            time = source[f"{split}_time"][()]
            if factors.ndim != 3 or factors.shape[:2] != time.shape:
                raise ValueError("Factor sequences do not match the saved timestamps.")
            arrays["latent"].append(factors.reshape(-1, factors.shape[-1]))
            arrays["time"].append(time.ravel())
            for key in ("segment_id", "sequence_id"):
                arrays[key].append(
                    np.repeat(source[f"{split}_{key}"][()], time.shape[1])
                )
            arrays["split"].append(np.full(time.size, label, dtype=np.int8))
    results = {key: np.concatenate(value) for key, value in arrays.items()}
    order = np.argsort(results["time"])
    results = {key: value[order] for key, value in results.items()}
    if not np.isfinite(results["latent"]).all() or np.any(
        np.diff(results["time"]) <= 0
    ):
        raise ValueError("Expected finite factors and unique increasing timestamps.")
    results.update(
        unit_index=unit_index,
        input_bin_seconds=np.asarray(bin_seconds),
        latent_step_seconds=np.asarray(bin_seconds),
    )
    output_path = Path(output_path).expanduser()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("xb") as output:
        np.savez_compressed(output, **results)
    return results
